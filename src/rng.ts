// Seeded PRNG (mulberry32) so flights are reproducible from a seed.

export type Rng = () => number;

export function createRng(seed: number): Rng {
  let state = seed >>> 0;
  return function next(): number {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function rangeFloat(rng: Rng, min: number, max: number): number {
  return min + rng() * (max - min);
}

export function rangeInt(rng: Rng, min: number, max: number): number {
  return Math.floor(rangeFloat(rng, min, max + 1));
}
